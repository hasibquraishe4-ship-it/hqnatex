type Direction =
  | "debit"
  | "credit";

type JournalLine = {
  id?: string;
  journal_entry?: string;
  account_code?: string;
  amount?: string | number;
  direction?: Direction | string;
};

type JournalEntry = {
  id: string;
  entry_number?: string;
  entry_date?: string;
  description?: string;
  status?: string;
  debit_total?: string | number;
  credit_total?: string | number;
  is_balanced?: boolean;
  lines?: JournalLine[];
};

type AccountRow = {
  id?: string;
  code?: string;
  name?: string;
  account_code?: string;
  account_name?: string;
  is_active?: boolean;
  is_posting?: boolean;
  status?: string;
};

type DraftLine = {
  accountCode: string;
  direction: Direction;
  amount: string;
};

type RecoveryState = {
  entryId: string | null;
  createAttempted: boolean;
};

